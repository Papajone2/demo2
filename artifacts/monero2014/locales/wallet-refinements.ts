export function withWalletRefinements(language: string, catalog: Record<string, string>) {
  const values = translations[language];
  if (!values) return catalog;
  if (values.length !== keys.length) throw new Error(`Incomplete wallet refinement translation: ${language}`);
  keys.forEach((key, index) => { catalog[key] = values[index]; });
  return catalog;
}
